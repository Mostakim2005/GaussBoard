/**
 * @file spice-engine.js
 * @description Switchable SPICE netlist compiler and ngspice-wasm / fallback sweep engine.
 * Designed to pair with IndustrialCircuitSim (MNA Live) without mutating circuit-sim.js
 * and without bundling ngspice-wasm inside src/vendor/ (loads from %LOCALAPPDATA%\SharedLibraries).
 */

export const SOLVER_MODES = {
  MNA_LIVE: 'mna-live',
  NGSPICE_SPICE: 'ngspice-spice'
};

const GROUND_PORTS = new Set(['N', 'PE', '-', 'GND', '0']);

function sanitizeSpiceId(raw) {
  const s = String(raw || 'X').replace(/[^A-Za-z0-9_]/g, '_');
  return s || 'X';
}

function getComponentsList(sim) {
  if (!sim || !sim.components) return [];
  if (sim.components instanceof Map) return [...sim.components.values()];
  if (Array.isArray(sim.components)) return sim.components;
  return Object.values(sim.components);
}

function buildNetResolver(sim) {
  const parent = new Map();
  const find = (k) => {
    if (!parent.has(k)) parent.set(k, k);
    let root = k;
    while (parent.get(root) !== root) root = parent.get(root);
    let cur = k;
    while (cur !== root) {
      const next = parent.get(cur);
      parent.set(cur, root);
      cur = next;
    }
    return root;
  };
  const union = (a, b) => {
    const ra = find(a);
    const rb = find(b);
    if (ra !== rb) parent.set(rb, ra);
  };

  const wires = Array.isArray(sim?.wires) ? sim.wires : [];
  for (const w of wires) {
    if (w?.from && w?.to) union(String(w.from), String(w.to));
  }

  const groundRoots = new Set();
  const comps = getComponentsList(sim);
  for (const c of comps) {
    const cid = c?.id;
    if (!cid) continue;
    for (const gp of GROUND_PORTS) {
      const key = `${cid}:${gp}`;
      if (parent.has(key)) groundRoots.add(find(key));
    }
  }
  for (const w of wires) {
    for (const ep of [w?.from, w?.to]) {
      if (!ep) continue;
      const port = String(ep).split(':')[1] || '';
      if (GROUND_PORTS.has(port)) groundRoots.add(find(String(ep)));
    }
  }

  const rootToNode = new Map();
  let nextIdx = 1;
  const nodeFor = (compId, portName) => {
    const ep = `${compId}:${portName}`;
    const r = find(ep);
    if (groundRoots.has(r) || GROUND_PORTS.has(portName)) {
      rootToNode.set(r, '0');
      return '0';
    }
    if (!rootToNode.has(r)) {
      rootToNode.set(r, `N${nextIdx++}`);
    }
    return rootToNode.get(r);
  };

  return { nodeFor, rootToNode };
}

/**
 * Compile an IndustrialCircuitSim topology into a SPICE (.cir) netlist.
 */
export function generateSpiceNetlist(sim, options = {}) {
  const analysis = options.analysis === 'ac' ? 'ac' : 'tran';
  const tStep = options.tStep || '0.1m';
  const tStop = options.tStop || '20m';
  const fStart = options.fStart || '10';
  const fStop = options.fStop || '100k';
  const title = options.title || 'GaussBoard Dual Circuit Netlist';

  const comps = getComponentsList(sim);
  const { nodeFor } = buildNetResolver(sim);
  const lines = [
    `* ${title}`,
    `* Generated by GaussBoard SPICE Engine (${new Date().toISOString()})`,
    ''
  ];
  const warnings = [];
  let hasDiode = false;
  let hasLed = false;
  let hasBjt = false;

  const freq = Number.isFinite(sim?.frequency) ? sim.frequency : 50;
  const v1pRms = Number.isFinite(sim?.gridVoltageRMS) ? sim.gridVoltageRMS : 230;
  const vDc = Number.isFinite(sim?.dcSupplyVoltage) ? sim.dcSupplyVoltage : 24;

  for (const comp of comps) {
    if (!comp || !comp.id) continue;
    const sid = sanitizeSpiceId(comp.id);
    switch (comp.type) {
      case 'dc_supply': {
        const pPos = nodeFor(comp.id, '+');
        const pNeg = nodeFor(comp.id, '-');
        lines.push(`V_${sid} ${pPos} ${pNeg} DC ${Number.isFinite(comp.voltage) ? comp.voltage : vDc}`);
        break;
      }
      case 'power_source_1p': {
        const pL = nodeFor(comp.id, 'L');
        const pN = nodeFor(comp.id, 'N');
        const vPeak = (v1pRms * Math.SQRT2).toFixed(2);
        lines.push(`V_${sid} ${pL} ${pN} SIN(0 ${vPeak} ${freq}) AC ${v1pRms} 0`);
        break;
      }
      case 'power_source_3p': {
        const p1 = nodeFor(comp.id, 'L1');
        const p2 = nodeFor(comp.id, 'L2');
        const p3 = nodeFor(comp.id, 'L3');
        const pN = nodeFor(comp.id, 'N');
        const vPeak = (v1pRms * Math.SQRT2).toFixed(2);
        lines.push(`V_${sid}_L1 ${p1} ${pN} SIN(0 ${vPeak} ${freq} 0 0 0) AC ${v1pRms} 0`);
        lines.push(`V_${sid}_L2 ${p2} ${pN} SIN(0 ${vPeak} ${freq} 0 0 -120) AC ${v1pRms} -120`);
        lines.push(`V_${sid}_L3 ${p3} ${pN} SIN(0 ${vPeak} ${freq} 0 0 -240) AC ${v1pRms} -240`);
        break;
      }
      case 'resistor': {
        const a = nodeFor(comp.id, '1');
        const b = nodeFor(comp.id, '2');
        lines.push(`R_${sid} ${a} ${b} ${Number.isFinite(comp.resistance) ? comp.resistance : 1000}`);
        break;
      }
      case 'capacitor': {
        const a = nodeFor(comp.id, '+');
        const b = nodeFor(comp.id, '-');
        lines.push(`C_${sid} ${a} ${b} ${Number.isFinite(comp.capacitance) ? comp.capacitance : 100e-6}`);
        break;
      }
      case 'inductor': {
        const a = nodeFor(comp.id, '1');
        const b = nodeFor(comp.id, '2');
        lines.push(`L_${sid} ${a} ${b} ${Number.isFinite(comp.inductance) ? comp.inductance : 10e-3}`);
        break;
      }
      case 'diode': {
        hasDiode = true;
        const a = nodeFor(comp.id, 'A');
        const k = nodeFor(comp.id, 'K');
        lines.push(`D_${sid} ${a} ${k} D1N4148`);
        break;
      }
      case 'led': {
        hasLed = true;
        const a = nodeFor(comp.id, 'A');
        const k = nodeFor(comp.id, 'K');
        lines.push(`D_${sid}_LED ${a} ${k} DLED`);
        break;
      }
      case 'bjt_npn': {
        hasBjt = true;
        const c = nodeFor(comp.id, 'C');
        const b = nodeFor(comp.id, 'B');
        const e = nodeFor(comp.id, 'E');
        lines.push(`Q_${sid} ${c} ${b} ${e} Q2N3904`);
        break;
      }
      case 'opamp': {
        const vp = nodeFor(comp.id, '+');
        const vn = nodeFor(comp.id, '-');
        const vo = nodeFor(comp.id, 'OUT');
        lines.push(`E_${sid} ${vo} 0 ${vp} ${vn} 1e5`);
        lines.push(`R_${sid}_IN ${vp} ${vn} 2e6`);
        break;
      }
      case 'breaker': {
        const closed = comp.closed && !comp.tripped;
        const poles = comp.poles === 1 ? [['1', '2']] : [['1', '2'], ['3', '4'], ['5', '6']];
        for (const [p1, p2] of poles) {
          lines.push(`R_${sid}_${p1}_${p2} ${nodeFor(comp.id, p1)} ${nodeFor(comp.id, p2)} ${closed ? '1e-3' : '1e9'}`);
        }
        break;
      }
      case 'pushbutton':
      case 'estop': {
        const closed = comp.kind === 'nc' ? !comp.pressed && !comp.latched : !!comp.pressed;
        const p1 = comp.kind === 'nc' ? '1' : '3';
        const p2 = comp.kind === 'nc' ? '2' : '4';
        lines.push(`R_${sid} ${nodeFor(comp.id, p1)} ${nodeFor(comp.id, p2)} ${closed ? '1e-3' : '1e9'}`);
        break;
      }
      case 'overload_relay': {
        const ncClosed = !comp.tripped;
        lines.push(`R_${sid}_NC ${nodeFor(comp.id, '95')} ${nodeFor(comp.id, '96')} ${ncClosed ? '1e-3' : '1e9'}`);
        lines.push(`R_${sid}_NO ${nodeFor(comp.id, '97')} ${nodeFor(comp.id, '98')} ${comp.tripped ? '1e-3' : '1e9'}`);
        break;
      }
      case 'contactor': {
        lines.push(`R_${sid}_COIL ${nodeFor(comp.id, 'A1')} ${nodeFor(comp.id, 'A2')} 250`);
        const on = !!comp.energized;
        for (const [p1, p2] of [['1', '2'], ['3', '4'], ['5', '6'], ['13', '14']]) {
          lines.push(`R_${sid}_${p1}_${p2} ${nodeFor(comp.id, p1)} ${nodeFor(comp.id, p2)} ${on ? '1e-3' : '1e9'}`);
        }
        lines.push(`R_${sid}_21_22 ${nodeFor(comp.id, '21')} ${nodeFor(comp.id, '22')} ${on ? '1e9' : '1e-3'}`);
        break;
      }
      case 'pilot_light': {
        lines.push(`R_${sid}_LAMP ${nodeFor(comp.id, 'X1')} ${nodeFor(comp.id, 'X2')} 2200`);
        break;
      }
      case 'motor': {
        const u = nodeFor(comp.id, 'U');
        const v = nodeFor(comp.id, 'V');
        const w = nodeFor(comp.id, 'W');
        const star = `N_${sid}_STAR`;
        lines.push(`R_${sid}_U ${u} ${star} 12`);
        lines.push(`R_${sid}_V ${v} ${star} 12`);
        lines.push(`R_${sid}_W ${w} ${star} 12`);
        break;
      }
      default: {
        warnings.push(`Behavioral macro approximated for ${comp.type}:${comp.id}`);
        lines.push(`* Component ${comp.type} (${comp.id}) approximated as behavioral block`);
        break;
      }
    }
  }

  if (hasDiode) lines.push('', '.model D1N4148 D(Is=2.52n Rs=0.568 N=1.752 Bv=100 Ibv=100u)');
  if (hasLed) lines.push('', '.model DLED D(Is=1e-18 N=2.2 Rs=4)');
  if (hasBjt) lines.push('', '.model Q2N3904 NPN(Is=6.734f Bf=200 Vaf=74.03)');

  lines.push('');
  if (analysis === 'ac') {
    lines.push(`.ac dec 20 ${fStart} ${fStop}`);
  } else {
    lines.push(`.tran ${tStep} ${tStop}`);
  }
  lines.push('.end');

  const nodeSet = new Set(['0']);
  for (const w of Array.isArray(sim?.wires) ? sim.wires : []) {
    if (w?.from) {
      const [cid, p] = String(w.from).split(':');
      nodeSet.add(nodeFor(cid, p));
    }
    if (w?.to) {
      const [cid, p] = String(w.to).split(':');
      nodeSet.add(nodeFor(cid, p));
    }
  }

  return {
    title,
    netlist: lines.join('\n'),
    analysis,
    nodes: [...nodeSet],
    componentCount: comps.length,
    warnings
  };
}

function buildFallbackTraces(sim, analysis) {
  const comps = getComponentsList(sim);
  const freq = Number.isFinite(sim?.frequency) ? sim.frequency : 50;
  const vDc = Number.isFinite(sim?.dcSupplyVoltage) ? sim.dcSupplyVoltage : 24;
  const hasAc = comps.some((c) => c.type === 'power_source_1p' || c.type === 'power_source_3p');
  const hasDiode = comps.some((c) => c.type === 'diode' || c.type === 'led');
  const hasCap = comps.some((c) => c.type === 'capacitor');
  const vPeak = hasAc ? (sim?.gridVoltageRMS || 230) * Math.SQRT2 : vDc;

  if (analysis === 'ac') {
    const xValues = [];
    const magDb = [];
    const phaseDeg = [];
    const fc = hasCap ? 159.15 : 1200;
    const points = 60;
    for (let i = 0; i < points; i++) {
      const f = Math.pow(10, 1 + (4 * i) / (points - 1)); // 10 Hz .. 100 kHz
      const ratio = f / fc;
      const mag = 1 / Math.sqrt(1 + ratio * ratio);
      xValues.push(Number(f.toFixed(2)));
      magDb.push(Number((20 * Math.log10(Math.max(1e-6, mag))).toFixed(2)));
      phaseDeg.push(Number(((-Math.atan(ratio) * 180) / Math.PI).toFixed(2)));
    }
    return {
      xLabel: 'Frequency (Hz)',
      xValues,
      traces: [
        { name: 'V(out) Gain (dB)', unit: 'dB', color: '#38bdf8', values: magDb },
        { name: 'Phase (deg)', unit: 'deg', color: '#f59e0b', values: phaseDeg }
      ]
    };
  }

  const xValues = [];
  const vSource = [];
  const vLoad = [];
  const points = 100;
  const tStopMs = 20;
  let capHold = 0;

  for (let i = 0; i < points; i++) {
    const tMs = (tStopMs * i) / (points - 1);
    const tSec = tMs / 1000;
    xValues.push(Number(tMs.toFixed(3)));
    const srcVal = hasAc
      ? vPeak * Math.sin(2 * Math.PI * freq * tSec)
      : vDc * (1 - Math.exp(-tSec / 0.002));
    vSource.push(Number(srcVal.toFixed(3)));

    let loadVal = srcVal;
    if (hasDiode) {
      loadVal = Math.max(0, Math.abs(srcVal) - 1.4);
    }
    if (hasCap) {
      capHold = loadVal >= capHold ? loadVal : capHold * Math.exp(-0.0002 / 0.01);
      loadVal = capHold;
    }
    vLoad.push(Number(loadVal.toFixed(3)));
  }

  return {
    xLabel: 'Time (ms)',
    xValues,
    traces: [
      { name: 'V(src)', unit: 'V', color: '#38bdf8', values: vSource },
      { name: 'V(load)', unit: 'V', color: '#10b981', values: vLoad }
    ]
  };
}

export class SpiceEngine {
  constructor() {
    this.mode = SOLVER_MODES.MNA_LIVE;
    this.runtime = {
      ngspice: { available: false, entryPath: null, sharedDir: null },
      tina: { available: false, executable: null }
    };
    this.lastResult = null;
  }

  setMode(mode) {
    this.mode = mode === SOLVER_MODES.NGSPICE_SPICE ? SOLVER_MODES.NGSPICE_SPICE : SOLVER_MODES.MNA_LIVE;
    return this.mode;
  }

  async detectRuntime({ boardApi = (typeof window !== 'undefined' ? window.board : null) } = {}) {
    try {
      if (typeof boardApi?.getSpiceStatus === 'function') {
        const status = await boardApi.getSpiceStatus();
        if (status && typeof status === 'object') {
          this.runtime = {
            ngspice: status.ngspice || { available: false, entryPath: null },
            tina: status.tina || { available: false, executable: null }
          };
        }
      }
    } catch {}
    return this.runtime;
  }

  async runAnalysis(sim, options = {}) {
    const compiled = generateSpiceNetlist(sim, options);
    const analysis = compiled.analysis;

    if (typeof options.wasmRunner === 'function') {
      const wasmOut = await options.wasmRunner(compiled.netlist, compiled);
      this.lastResult = {
        ok: true,
        engine: 'ngspice-wasm',
        wasmInstalled: true,
        analysis,
        netlist: compiled.netlist,
        warnings: compiled.warnings,
        ...wasmOut
      };
      return this.lastResult;
    }

    if (this.runtime?.ngspice?.available && this.runtime.ngspice.entryPath) {
      try {
        const entry = String(this.runtime.ngspice.entryPath).replace(/\\/g, '/');
        const url = entry.startsWith('file://') ? entry : (/^[a-zA-Z]:/.test(entry) ? `file:///${entry}` : `file://${entry}`);
        const mod = await import(/* @vite-ignore */ url);
        const runner = mod?.Simulation || mod?.default?.Simulation || mod?.runSpice;
        if (typeof runner === 'function') {
          const out = await runner(compiled.netlist);
          if (out && Array.isArray(out.traces)) {
            this.lastResult = {
              ok: true,
              engine: 'ngspice-wasm',
              wasmInstalled: true,
              analysis,
              netlist: compiled.netlist,
              warnings: compiled.warnings,
              ...out
            };
            return this.lastResult;
          }
        }
      } catch (err) {
        compiled.warnings.push(`ngspice-wasm fallback active: ${err?.message || err}`);
      }
    }

    const sweep = buildFallbackTraces(sim, analysis);
    this.lastResult = {
      ok: true,
      engine: 'spice-js-fallback',
      wasmInstalled: !!this.runtime?.ngspice?.available,
      analysis,
      netlist: compiled.netlist,
      warnings: compiled.warnings,
      ...sweep
    };
    return this.lastResult;
  }
}

export async function exportSpiceNetlistFile(sim, options = {}) {
  const compiled = generateSpiceNetlist(sim, options);
  const filename = options.filename || 'gaussboard-circuit.cir';
  const bytes = new TextEncoder().encode(compiled.netlist);

  if (typeof window !== 'undefined' && window.board?.saveDialog && window.board?.writeFile) {
    const targetPath = options.filePath || await window.board.saveDialog({
      title: 'Export .cir Netlist',
      defaultPath: filename,
      filters: [
        { name: 'SPICE Netlist (*.cir)', extensions: ['cir', 'sp'] },
        { name: 'All Files', extensions: ['*'] }
      ]
    });
    if (!targetPath) return { ok: false, cancelled: true, netlist: compiled.netlist };
    await window.board.writeFile(targetPath, bytes.buffer);
    return { ok: true, filePath: targetPath, netlist: compiled.netlist };
  }

  if (typeof document !== 'undefined') {
    const blob = new Blob([bytes], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  }
  return { ok: true, filePath: filename, netlist: compiled.netlist };
}
